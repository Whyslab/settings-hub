"""Monitors: resolution, refresh rate, scale, on/off (Hyprland 0.57+, Lua).

A change is tried live first (`hyprctl eval 'hl.monitor({...})'`, success is
exactly "ok"); the page then asks whether to keep it and puts the old values
back if nobody answers. Kept values go to:

* monitors.json in the state dir: {output: {"mode", "scale", "position",
  "enabled"}} -- every output this page has set;
* ~/.config/hypr/settings-hub-monitors.lua -- one hl.monitor() per output,
  loaded by settings-hub.lua, so the setting survives a reboot.

History stores one key per output, MONITOR_KEY + name, whose value is the
whole setting dict; undo applies the old dict live and saves it.

No GTK.
"""

from __future__ import annotations

import json
import logging
import os
import re
import subprocess
import tempfile
import time
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from ..hypr import loads_settings_hub, lua_str

log = logging.getLogger(__name__)

BACKEND = "monitor"  # History backend name
WORKER = "monitor"
MONITOR_KEY = "monitor."
LUA_FILE = "settings-hub-monitors.lua"
RETRY_PAUSE_S = 0.5
SCALES = (1.0, 1.2, 1.25, 1.5, 1.6, 2.0, 2.5, 3.0)
LUA_HEADER = """\
-- Generated by settings-hub: the Monitor page's settings.
-- The Settings window rewrites this file; settings-hub.lua loads it.
"""

Runner = Callable[[list[str]], tuple[int, str]]


def run_hyprctl(args: list[str]) -> tuple[int, str]:
    try:
        done = subprocess.run(["hyprctl", *args], capture_output=True, text=True, timeout=10,
                              stdin=subprocess.DEVNULL, check=False)
    except (OSError, subprocess.SubprocessError) as exc:
        log.warning("hyprctl %s: %s", args[:1], exc)
        return 127, ""
    return done.returncode, done.stdout


def state_path() -> Path:
    base = os.environ.get("XDG_STATE_HOME") or str(Path.home() / ".local" / "state")
    return Path(base) / "settings-hub" / "monitors.json"


def hypr_dir() -> Path:
    base = os.environ.get("XDG_CONFIG_HOME") or str(Path.home() / ".config")
    return Path(base) / "hypr"


_MODE = re.compile(r"^(\d{2,5})x(\d{2,5})@(\d{1,3}(?:\.\d{1,3})?)(?:Hz)?$")
_POSITION = re.compile(r"^-?\d{1,6}x-?\d{1,6}$")
_NAME = re.compile(r"^[A-Za-z0-9_.:-]{1,40}$")


def mode_text(width: int, height: int, rate: float) -> str:
    return f"{width}x{height}@{rate:.2f}"


def parse_mode(text: str) -> tuple[int, int, float] | None:
    m = _MODE.match(text.strip())
    if not m:
        return None
    return int(m.group(1)), int(m.group(2)), float(m.group(3))


def scales_for(width: int, height: int, current: float) -> list[float]:
    """Scales that divide the resolution into whole logical pixels (others
    Hyprland itself would round to a nearby one), plus the current one."""
    def whole(size: int, s: float) -> bool:
        return abs(size / s - round(size / s)) < 1e-6

    out = [s for s in SCALES if whole(width, s) and whole(height, s)]
    if current and all(abs(current - s) > 1e-3 for s in out):
        out.append(round(current, 4))
    return sorted(out)


def clean_setting(raw: Any) -> dict[str, Any] | None:
    """A setting as this module writes it, or None if it is not one."""
    if not isinstance(raw, dict):
        return None
    mode = raw.get("mode")
    scale = raw.get("scale")
    position = raw.get("position")
    enabled = raw.get("enabled", True)
    if not isinstance(mode, str) or parse_mode(mode) is None:
        return None
    if isinstance(scale, bool) or not isinstance(scale, (int, float)) or not 0.25 <= scale <= 4:
        return None
    if not isinstance(position, str) or not _POSITION.match(position):
        return None
    if not isinstance(enabled, bool):
        return None
    transform = raw.get("transform", 0)
    if isinstance(transform, bool) or not isinstance(transform, int) or not 0 <= transform <= 7:
        return None
    parsed = parse_mode(mode)
    assert parsed is not None  # checked above
    return {"mode": mode_text(*parsed), "scale": round(float(scale), 4),
            "position": position, "enabled": enabled, "transform": transform}


def lua_call(name: str, setting: dict[str, Any]) -> str:
    if not setting["enabled"]:
        return f"hl.monitor({{ output = {lua_str(name)}, disabled = true }})"
    # transform is carried: a rule without it would turn a rotated screen back
    return (f"hl.monitor({{ output = {lua_str(name)}, mode = {lua_str(setting['mode'])}, "
            f"position = {lua_str(setting['position'])}, scale = {setting['scale']:g}, "
            f"transform = {setting.get('transform', 0)} }})")


def build_lua(state: dict[str, dict[str, Any]]) -> str:
    if not state:
        return LUA_HEADER + "-- Nothing set: Hyprland decides.\n"
    return LUA_HEADER + "".join(lua_call(n, s) + "\n" for n, s in sorted(state.items()))


@dataclass
class Monitor:
    name: str
    description: str
    width: int
    height: int
    rate: float
    scale: float
    x: int
    y: int
    enabled: bool
    modes: list[str] = field(default_factory=list)  # "1920x1080@60.02"
    transform: int = 0

    def setting(self) -> dict[str, Any]:
        return {"mode": mode_text(self.width, self.height, self.rate),
                "scale": round(self.scale, 4), "position": f"{self.x}x{self.y}",
                "enabled": self.enabled, "transform": self.transform}


def parse_monitors(text: str) -> list[Monitor]:
    try:
        raw = json.loads(text)
    except ValueError:
        return []
    out = []
    for m in raw if isinstance(raw, list) else []:
        if not isinstance(m, dict) or not _NAME.match(str(m.get("name", ""))):
            continue
        modes = []
        for mode in m.get("availableModes") or []:
            parsed = parse_mode(str(mode))
            if parsed:
                text_mode = mode_text(*parsed)
                if text_mode not in modes:
                    modes.append(text_mode)
        try:
            monitor = Monitor(
                name=str(m["name"]), description=str(m.get("description") or ""),
                width=int(m["width"]), height=int(m["height"]),
                rate=float(m.get("refreshRate") or 60), scale=float(m.get("scale") or 1),
                x=int(m.get("x") or 0), y=int(m.get("y") or 0),
                enabled=not m.get("disabled", False), modes=modes,
                transform=int(m.get("transform") or 0) % 8)
        except (KeyError, TypeError, ValueError):
            continue
        if monitor.width < 10 or monitor.height < 10:  # a disabled output may say 0x0
            if not modes:
                continue
            monitor.width, monitor.height, monitor.rate = parse_mode(modes[0]) or (0, 0, 60.0)
        current = mode_text(monitor.width, monitor.height, monitor.rate)
        if current not in monitor.modes:
            monitor.modes.insert(0, current)
        out.append(monitor)
    return out


@dataclass
class Info:
    monitors: list[Monitor] = field(default_factory=list)
    lua: bool = False  # the session takes hl.monitor (Hyprland 0.57+)
    loaded: bool = True  # settings-hub.lua loads our file


def _atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(text)
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


class Backend:
    def __init__(self, workers, hyprctl: Runner | None = None,
                 state_file: Path | None = None, hypr: Path | None = None) -> None:
        self.workers = workers
        self.hyprctl = hyprctl or run_hyprctl
        self.state_file = state_file or state_path()
        self.hypr = hypr or hypr_dir()
        self.lua_file = self.hypr / LUA_FILE

    # ---- reading ---------------------------------------------------------

    def monitors(self) -> list[Monitor]:
        rc, out = self.hyprctl(["monitors", "all", "-j"])
        return parse_monitors(out) if rc == 0 else []

    def lua_session(self) -> bool:
        rc, out = self.hyprctl(["-j", "version"])
        try:
            version = str(json.loads(out).get("version", "")) if rc == 0 else ""
        except (ValueError, AttributeError):
            return False
        parts = re.findall(r"\d+", version)[:2]
        return len(parts) == 2 and (int(parts[0]), int(parts[1])) >= (0, 57)

    def probe(self) -> Info:
        info = Info(monitors=self.monitors(), lua=self.lua_session())
        try:
            own = (self.hypr / "settings-hub.lua").read_text(encoding="utf-8")
            main = (self.hypr / "hyprland.lua").read_text(encoding="utf-8")
            info.loaded = LUA_FILE in own and loads_settings_hub(main)
        except OSError:
            info.loaded = False
        return info

    def load(self) -> dict[str, dict[str, Any]]:
        try:
            raw = json.loads(self.state_file.read_text(encoding="utf-8"))
        except FileNotFoundError:
            return {}
        except (OSError, ValueError) as exc:
            log.warning("reading %s: %s", self.state_file, exc)
            return {}
        out = {}
        for name, setting in raw.items() if isinstance(raw, dict) else []:
            clean = clean_setting(setting)
            if clean is not None and _NAME.match(str(name)):
                out[str(name)] = clean
        return out

    # ---- changing --------------------------------------------------------

    def try_live(self, name: str, setting: dict[str, Any]) -> None:
        """Set it in the running session only; RuntimeError if Hyprland refused."""
        clean = clean_setting(setting)
        if clean is None or not _NAME.match(name):
            raise ValueError(f"{name}: {setting!r}")
        rc, out = self.hyprctl(["eval", lua_call(name, clean)])
        if out.strip() != "ok":
            raise RuntimeError(out.strip() or f"hyprctl eval: {rc}")

    def restore(self, name: str, setting: dict[str, Any], tries: int = 3) -> None:
        """Put a setting back live; when Hyprland does not take it, reload the
        config (the unconfirmed setting is in no file, so that brings back the
        saved one). RuntimeError only if even that fails."""
        error: Exception | None = None
        for attempt in range(tries):
            if attempt:
                time.sleep(RETRY_PAUSE_S)  # a modeset may still be settling
            try:
                self.try_live(name, setting)
                return
            except (RuntimeError, ValueError) as exc:
                error = exc
        rc, out = self.hyprctl(["reload", "config-only"])
        if rc != 0:
            raise RuntimeError(f"{error}; hyprctl reload: {out.strip() or rc}")

    def save(self, name: str, setting: dict[str, Any]) -> None:
        clean = clean_setting(setting)
        if clean is None or not _NAME.match(name):
            raise ValueError(f"{name}: {setting!r}")
        state = self.load()
        state[name] = clean
        _atomic_write(self.state_file, json.dumps(state, indent=1) + "\n")
        _atomic_write(self.lua_file, build_lua(state))

    # History's Applier
    def read(self, keys: list[str]) -> dict[str, Any]:
        by_name = {m.name: m for m in self.monitors()}
        out = {}
        for key in keys:
            monitor = by_name.get(key[len(MONITOR_KEY):]) if key.startswith(MONITOR_KEY) else None
            if monitor is not None:
                out[key] = monitor.setting()
        return out

    def apply(self, values: dict[str, Any]) -> None:
        for key, setting in values.items():
            if key.startswith(MONITOR_KEY):
                name = key[len(MONITOR_KEY):]
                self.try_live(name, setting)
                self.save(name, setting)


def register(history, backend: Backend) -> Backend:
    history.register(BACKEND, backend)
    return backend
