"""Autostart: programs started at login, the window's own list and the config's.

The person's own list is kept like the Game binds list:

* autostart.json in the state dir: {"items": [{"name", "command"}]} -- what
  the page shows and History stores (key KEY, the whole list);
* ~/.config/hypr/settings-hub-autostart.lua -- settings-hub.lua loads it, and
  it runs each command with hl.exec_cmd in hl.on("hyprland.start"). A change
  counts from the next login (the start event has passed); nothing is reloaded.

What hyprland.lua itself starts is read in luaread's sandbox (nothing is run)
and only shown: those lines are the config's to change.

No GTK.
"""

from __future__ import annotations

import json
import logging
import os
import re
import shlex
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from ..binds import luaread
from ..hypr import loads_settings_hub, lua_str

log = logging.getLogger(__name__)

BACKEND = "autostart"  # History backend name
KEY = "autostart"  # the one History key: the whole list
WORKER = "autostart"
LUA_FILE = "settings-hub-autostart.lua"
MAX_ITEMS = 30
MAX_COMMAND = 300
MAX_NAME = 80

LUA_HEADER = """\
-- Generated by settings-hub: the Autostart page's own programs.
-- The Settings window rewrites this file; settings-hub.lua loads it.
"""

# Desktop-entry field codes (%f %U %i …) are for launchers that pass files;
# at login there are none.
_FIELD_CODE = re.compile(r"\s*%[fFuUdDnNickvm]")


def state_path() -> Path:
    base = os.environ.get("XDG_STATE_HOME") or str(Path.home() / ".local" / "state")
    return Path(base) / "settings-hub" / "autostart.json"


def hypr_dir() -> Path:
    base = os.environ.get("XDG_CONFIG_HOME") or str(Path.home() / ".config")
    return Path(base) / "hypr"


def command_from_exec(exec_line: str) -> str:
    """A desktop entry's Exec= as a command to run at login (no field codes)."""
    return _FIELD_CODE.sub("", exec_line).replace("%%", "%").strip()


def clean_command(text: Any) -> str | None:
    if not isinstance(text, str):
        return None
    text = text.strip()  # spacing inside is kept: it may be inside quotes
    if not text or len(text) > MAX_COMMAND or any(c in text for c in "\n\r\0"):
        return None
    try:
        shlex.split(text)  # exec_cmd runs it through sh: unbalanced quotes would fail there
    except ValueError:
        return None
    return text


def normalize(raw: Any) -> dict[str, Any]:
    items: list[dict[str, str]] = []
    seen: set[str] = set()
    source = raw.get("items") if isinstance(raw, dict) else None
    for item in source if isinstance(source, list) else []:
        if not isinstance(item, dict):
            continue
        command = clean_command(item.get("command"))
        if command is None or command in seen:
            continue
        name = item.get("name")
        name = " ".join(name.split())[:MAX_NAME] if isinstance(name, str) else ""
        seen.add(command)
        items.append({"name": name, "command": command})
        if len(items) >= MAX_ITEMS:
            break
    return {"items": items}


def build_lua(state: dict[str, Any]) -> str:
    items = normalize(state)["items"]
    if not items:
        return LUA_HEADER + "-- Nothing yet.\n"
    lines = [LUA_HEADER, 'hl.on("hyprland.start", function()\n']
    for item in items:
        note = f"  -- {item['name']}" if item["name"] else ""
        lines.append(f"    hl.exec_cmd({lua_str(item['command'])}){note}\n")
    lines.append("end)\n")
    return "".join(lines)


def _atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(text)
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


NOTE_MAX = 80
OWN_FILES = ("settings-hub.lua", LUA_FILE)  # the window's own lines are not the config's


def short_note(comment: str) -> str:
    """The first sentence of a comment, clipped: a comment block above a line
    may be a paragraph, or be about something else entirely."""
    text = " ".join(comment.split())
    for stop in (". ", ": ", "; "):
        if stop in text:
            text = text.split(stop, 1)[0]
    return text if len(text) <= NOTE_MAX else text[:NOTE_MAX - 1].rstrip() + "…"


def short_command(command: str) -> str:
    home = str(Path.home())
    return command.replace(home + "/", "~/") if home not in ("", "/") else command


@dataclass(frozen=True)
class SystemStart:
    command: str
    name: str  # first sentence of the comment on or above its line ("" if none)
    file: str
    line: int


@dataclass
class Info:
    state: dict[str, Any] = field(default_factory=lambda: {"items": []})
    system: list[SystemStart] | None = None  # None: hyprland.lua could not be read
    loaded: bool = True  # settings-hub.lua loads our file


def system_starts(lua: Path, own: Path) -> list[SystemStart] | None:
    """What hyprland.lua starts at login, without the lines of our own file."""
    starts = luaread.read_starts(lua)
    if starts is None:
        return None
    files: dict[str, list[str]] = {}
    out = []
    for s in starts:
        if s.file and Path(s.file).name in OWN_FILES + (own.name,):
            continue
        name = ""
        if s.file:
            if s.file not in files:
                try:
                    files[s.file] = Path(s.file).read_text(encoding="utf-8").splitlines()
                except OSError:
                    files[s.file] = []
            trailing, above = luaread.comments(files[s.file], s.line)
            name = short_note(trailing or above)
        out.append(SystemStart(s.command, name, s.file, s.line))
    return out


class Backend:
    def __init__(self, workers, state_file: Path | None = None,
                 hypr: Path | None = None) -> None:
        self.workers = workers
        self.state_file = state_file or state_path()
        self.hypr = hypr or hypr_dir()
        self.lua_file = self.hypr / LUA_FILE

    # History's Applier
    def read(self, keys: list[str]) -> dict[str, Any]:
        return {k: self.load() for k in keys if k == KEY}

    def apply(self, values: dict[str, Any]) -> None:
        if KEY in values:
            self.save(values[KEY])

    def load(self) -> dict[str, Any]:
        try:
            raw = json.loads(self.state_file.read_text(encoding="utf-8"))
        except FileNotFoundError:
            raw = None
        except (OSError, ValueError) as exc:
            log.warning("reading %s: %s", self.state_file, exc)
            raw = None
        return normalize(raw)

    def save(self, state: dict[str, Any]) -> None:
        state = normalize(state)
        _atomic_write(self.state_file, json.dumps(state, ensure_ascii=False, indent=1) + "\n")
        _atomic_write(self.lua_file, build_lua(state))

    def probe(self) -> Info:
        info = Info(state=self.load())
        main = self.hypr / "hyprland.lua"
        if main.is_file():
            info.system = system_starts(main, self.lua_file)
        try:
            own_lua = (self.hypr / "settings-hub.lua").read_text(encoding="utf-8")
            info.loaded = LUA_FILE in own_lua and loads_settings_hub(
                main.read_text(encoding="utf-8"))
        except OSError:
            info.loaded = False
        return info


def register(history, backend: Backend) -> Backend:
    history.register(BACKEND, backend)
    return backend
