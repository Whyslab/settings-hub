"""Write binds: only inside settings-hub's block of settings-hub.conf. No GTK.

    # >>> settings-hub binds
    unbind = ALT, Tab  # hyprland.conf:138
    bind = ALT, grave, cyclenext,  # hyprland.conf:138
    bind = ALT, grave, bringactivetotop,  # hyprland.conf:139
    # <<< settings-hub binds

The block is read as lines per key combination; the History key of a
combination is "MODS, KEY" ('SUPER SHIFT, K') and its value is the list of
block lines for it. Nothing outside the markers is ever changed; hyprland.conf
is only read.

`unbind = MODS, KEY` is taken to remove *every* earlier bind of that modmask and
key spelling (that is what Hyprland's removeKeybind does). So the lines for a
combination are computed from what it should end up doing:

    rebind     old: unbind; new: every action of the old one, each with its own
               keyword (bindl stays bindl, bindel stays bindel)
    disable    unbind + the remaining actions again
    add        bind (an occupied combination is unbound first: "Replace")
    revert     no lines: the config files decide again

lines_for() parses the config without our lines for the combination; if that
already does what is wanted, no lines are needed; otherwise unbind (one per key
spelling found) + the wanted binds. Every line ends in a comment with the
file:line it came from ("settings-hub" for an added bind). After composing,
the result is parsed again and must do exactly what was wanted (a file sourced
after settings-hub.conf could still redefine the combination).

commit(): atomic write -> `hyprctl reload` -> `hyprctl configerrors`; if new
errors appear, the previous text goes back, reload again, ConfigErrors. Writing
what is already there changes nothing and calls nothing. With hyprland.lua
present Hyprland does not read .conf at all: LuaActive, nothing is written.
"""

