# The window rule matches the main window by its title too: dialogs (Gtk.AlertDialog)
# have the same class but another title, and must keep their own size.
HEADER = """\
# Generated by settings-hub. The binds block is edited by the Settings window.
exec-once = python3 {data}/settings-hub/app.py --daemon
windowrule = match:class {cls}, match:initial_title {title}, float true, size 920 640, \
center true
windowrule = match:class {cls}, match:modal true, float true, center true
unbind = SUPER SHIFT, N
bind   = SUPER SHIFT, N, exec, {bin}/settings-open screen-sleep
unbind = SUPER SHIFT, W
bind   = SUPER SHIFT, W, exec, {bin}/settings-open wallpaper
bind   = SUPER, I, exec, {bin}/settings-open
submap = settings-hub-capture
bind   = SUPER CTRL ALT, Escape, submap, reset
submap = reset
"""
WINDOW_CLASS = r"^(settings-hub|io\.github\.whyslab\.SettingsHub)$"


def conf_text(data_home: str, bin_home: str, block: list[str] | None = None) -> str:
    """settings-hub.conf: the generated part, then the binds block (`block`: the
    lines between the markers, kept verbatim; empty if None)."""
    title = "^(" + re.escape(strings.APP_TITLE) + ")$"
    head = HEADER.format(data=data_home, bin=bin_home, cls=WINDOW_CLASS, title=title)
    return head + "\n".join([BEGIN, *(block or []), END]) + "\n"


TEMPLATE = conf_text("~/.local/share", "~/.local/bin")

# Hyprland 0.57+ reads hyprland.lua and no .conf at all; settings-hub.lua says
# the same as HEADER. The page shows binds read-only under Lua, so the block
# between the markers stays empty (kept for the Lua bind editor to come).
LUA_BEGIN, LUA_END = "-- >>> settings-hub binds", "-- <<< settings-hub binds"
LUA_HEADER = """\
-- Generated by settings-hub (a reinstall writes it again).
hl.on("hyprland.start", function()
    hl.exec_cmd({daemon})
end)
hl.window_rule({{
    name   = "settings-hub",
    match  = {{ class = {cls}, initial_title = {title} }},
    float  = true,
    size   = "920 640",
    center = true,
}})
hl.window_rule({{
    name   = "settings-hub-dialogs",
    match  = {{ class = {cls}, modal = true }},
    float  = true,
    center = true,
}})
hl.unbind("SUPER + SHIFT + N")
hl.bind("SUPER + SHIFT + N", hl.dsp.exec_cmd({open_screen}))
hl.unbind("SUPER + SHIFT + W")
hl.bind("SUPER + SHIFT + W", hl.dsp.exec_cmd({open_wallpaper}))
hl.bind("SUPER + I", hl.dsp.exec_cmd({open_any}))
hl.define_submap("settings-hub-capture", function()
    hl.bind("SUPER + CTRL + ALT + Escape", hl.dsp.submap("reset"))
end)
"""


def lua_text(data_home: str, bin_home: str) -> str:
    """settings-hub.lua. Paths are shell-quoted inside the commands (exec_cmd
    runs them through sh) and every string is a Lua literal."""
    title = "^(" + re.escape(strings.APP_TITLE) + ")$"
    app = shlex.quote(f"{data_home}/settings-hub/app.py")
    opener = shlex.quote(f"{bin_home}/settings-open")
    head = LUA_HEADER.format(
        daemon=hypr.lua_str(f"python3 {app} --daemon"),
        cls=hypr.lua_str(WINDOW_CLASS), title=hypr.lua_str(title),
        open_screen=hypr.lua_str(f"{opener} screen-sleep"),
        open_wallpaper=hypr.lua_str(f"{opener} wallpaper"),
        open_any=hypr.lua_str(opener),
    )
    return head + LUA_BEGIN + "\n" + LUA_END + "\n"


class WriterError(Exception):
    pass


class LuaActive(WriterError):
    def __init__(self, path: Path) -> None:
        super().__init__(str(path))
        self.path = path


class NoBlock(WriterError):
    pass


class ConfigErrors(WriterError):
    def __init__(self, errors: list[str]) -> None:
        super().__init__("; ".join(errors))
        self.errors = errors


class LaterDefinition(WriterError):
    def __init__(self, key: str, where: str) -> None:
        super().__init__(f"{key}: {where}")
        self.key, self.where = key, where


# ---- lines ------------------------------------------------------------------


@dataclass(frozen=True)
class Want:
    """One bind line to write, without its key combination."""

    keyword: str
    rest: str  # after "MODS, KEY," as Hyprland reads it (`##` escapes kept)
    origin: str

    def action(self) -> tuple[str, str, str, str]:
        parsed = parser.parse_bind_value(self.keyword, "X, Y," + self.rest.replace("##", "#"))
        _mods, _key, desc, dispatcher, arg = parsed
        return (self.keyword, dispatcher, arg, desc)


def want_of(bind: Bind, cfg: Config) -> Want:
    return Want(bind.keyword, bind.rest, bind.origin or cfg.where(bind))


def want_exec(command: str) -> Want:
    return Want("bind", " exec, " + " ".join(command.split()).replace("#", "##"), ADDED)


def bind_line(want: Want, mask: int, key: str) -> str:
    rest = want.rest if want.rest.startswith(" ") else " " + want.rest
    return f"{want.keyword} = {mods_text(mask)}, {key},{rest}  # {want.origin}"


def unbind_line(mask: int, key: str, origin: str) -> str:
    return f"unbind = {mods_text(mask)}, {key}  # {origin}"


def line_combo(line: str) -> Combo | None:
    code = split_comment(line)[0].strip()
    keyword, eq, value = code.partition("=")
    keyword = keyword.strip()
    if not eq:
        return None
    value = value.replace("##", "#")
    if keyword == "unbind":
        mods, _, key = value.partition(",")
        return Combo.of(mods, key)
    if parser._BIND_KW.match(keyword):
        parsed = parser.parse_bind_value(keyword, value)
        return Combo.of(parsed[0], parsed[1]) if parsed else None
    return None


# ---- the block --------------------------------------------------------------


def split(text: str) -> tuple[list[str], list[str], list[str]]:
    """(lines before the block, block lines, lines after) - markers belong to before/after."""
    lines = text.splitlines()
    starts = [i for i, line in enumerate(lines) if line.strip() == BEGIN]
    ends = [i for i, line in enumerate(lines) if line.strip() == END]
    if len(starts) != 1 or len(ends) != 1 or ends[0] < starts[0]:
        raise NoBlock("markers")
    s, e = starts[0], ends[0]
    return lines[:s + 1], lines[s + 1:e], lines[e:]


def _combos(block: list[str]) -> list[Combo | None]:
    """Each block line's combination; None for other lines and inside submap sections."""
    out: list[Combo | None] = []
    submap = False
    for line in block:
        code = split_comment(line)[0].strip()
        keyword, _, value = code.partition("=")
        if keyword.strip() == "submap":
            submap = value.split(",", 1)[0].strip() != "reset"
            out.append(None)
            continue
        out.append(None if submap else line_combo(line))
    return out


def block_lines(text: str, key: str) -> list[str]:
    _, block, _ = split(text)
    combo = Combo.parse(key)
    return [line for line, c in zip(block, _combos(block), strict=True) if c == combo]


def with_lines(text: str, key: str, lines: list[str]) -> str:
    """The text with the block lines of `key` replaced by `lines` (in place)."""
    before, block, after = split(text)
    combo = Combo.parse(key)
    hits = [i for i, c in enumerate(_combos(block)) if c == combo]
    if hits:
        at = hits[0]
        block = [line for i, line in enumerate(block) if i not in hits]
    else:
        at = len(block)
    block[at:at] = list(lines)
    return "\n".join(before + block + after) + "\n"


def apply_lines(text: str, changes: dict[str, list[str]]) -> str:
    for key, lines in changes.items():
        text = with_lines(text, key, lines)
    return text


# ---- planning ---------------------------------------------------------------


class Planner:
    """Computes block lines against the config as it is on disk (plus `text`)."""

    def __init__(self, main: Path, own: Path, text: str) -> None:
        self.main, self.own, self.text = Path(main), Path(own), text

    def parse(self, text: str | None = None) -> Config:
        return parser.parse(self.main, self.own, {self.own: self.text if text is None else text})

    def effective(self, cfg: Config, combo: Combo) -> list[Bind]:
        return [b for b in cfg.binds if not b.submap and b.combo == combo]

    def lines_for(self, mask: int, key: str, wants: list[Want]) -> list[str]:
        k = parser.combo_text(mask, key)
        cfg = self.parse(with_lines(self.text, k, []))
        base = self.effective(cfg, Combo.of(mask, key))
        if [b.action() for b in base] == [w.action() for w in wants]:
            return []
        lines: list[str] = []
        if base:
            spellings: list[str] = []
            for b in base:
                if b.key not in spellings:
                    spellings.append(b.key)
            origin = base[0].origin or cfg.where(base[0])
            lines += [unbind_line(mask, s, origin) for s in spellings]
        return lines + [bind_line(w, mask, key) for w in wants]

    def check(self, text: str, expected: dict[str, list[Want]]) -> None:
        """The composed text must do exactly what was wanted."""
        cfg = self.parse(text)
        for key, wants in expected.items():
            got = self.effective(cfg, Combo.parse(key))
            if [b.action() for b in got] != [w.action() for w in wants]:
                late = [b for b in got if not b.managed] or got
                where = cfg.where(late[-1]) if late else key
                raise LaterDefinition(key, where)

    # ---- operations: each returns ({key: lines}, {key: wants to check}) ----

    def rebind(self, entry: Entry, mask: int, key: str, cfg: Config):
        wants = [want_of(b, cfg) for b in entry.binds]
        new_key = parser.combo_text(mask, key)
        return ({entry.key: self.lines_for(entry.binds[0].modmask, entry.binds[0].key, []),
                 new_key: self.lines_for(mask, key, wants)},
                {entry.key: [], new_key: wants})

    def disable(self, entry: Entry, drop: list[Bind], cfg: Config):
        wants = [want_of(b, cfg) for b in entry.binds if b not in drop]
        first = entry.binds[0]
        return ({entry.key: self.lines_for(first.modmask, first.key, wants)}, {entry.key: wants})

    def add(self, mask: int, key: str, command: str):
        wants = [want_exec(command)]
        k = parser.combo_text(mask, key)
        return {k: self.lines_for(mask, key, wants)}, {k: wants}

    def revert(self, keys: list[str]):
        return {k: [] for k in keys}, {}


# ---- committing -------------------------------------------------------------


@dataclass
class Commit:
    before: dict[str, list[str]]
    after: dict[str, list[str]]
    changed: bool
    reloaded: bool = True


def configerrors(hyprctl: Runner) -> list[str]:
    rc, out = hyprctl(["configerrors"])
    if rc != 0:
        return []
    return [line.strip() for line in out.splitlines() if line.strip()]


def atomic_write(path: Path, text: str) -> None:
    path = Path(os.path.realpath(path))  # a symlinked file keeps its link
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        mode = path.stat().st_mode & 0o777
    except FileNotFoundError:
        mode = 0o644
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), prefix=f".{path.name}.")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(text)
            fh.flush()
            os.fsync(fh.fileno())
        os.chmod(tmp, mode)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def read_own(own: Path) -> tuple[str, bool]:
    """(text, exists); a missing file reads as the template."""
    try:
        return own.read_text(encoding="utf-8"), True
    except FileNotFoundError:
        return TEMPLATE, False


def commit(own: Path, changes: dict[str, list[str]], hyprctl: Runner,
           lua: Path | None = None, planner: Planner | None = None,
           expected: dict[str, list[Want]] | None = None) -> Commit:
    if lua is not None and lua.exists():
        raise LuaActive(lua)
    old, exists = read_own(own)
    before = {k: block_lines(old, k) for k in changes}
    new = apply_lines(old, changes)
    after = {k: block_lines(new, k) for k in changes}
    if new == old or (not exists and before == after):
        return Commit(before, after, changed=False)
    if planner is not None and expected:
        planner.check(new, expected)
    errors_before = set(configerrors(hyprctl))
    atomic_write(own, new)
    rc, _ = hyprctl(["reload"])
    errors = [e for e in configerrors(hyprctl) if e not in errors_before]
    if errors:
        if exists:
            atomic_write(own, old)
        else:
            own.unlink(missing_ok=True)
        hyprctl(["reload"])
        raise ConfigErrors(errors)
    return Commit(before, after, changed=True, reloaded=rc == 0)


def regenerate(text: str, data_home: str, bin_home: str) -> str:
    """A fresh generated part above the binds block of `text`; the block and
    everything after it are kept byte for byte. NoBlock if the markers are damaged."""
    split(text)  # exactly one BEGIN before exactly one END, or NoBlock
    lines = text.splitlines(keepends=True)
    start = next(i for i, line in enumerate(lines) if line.strip() == BEGIN)
    kept = "".join(lines[start:])
    head = conf_text(data_home, bin_home).split(BEGIN)[0]
    return head + kept + ("" if kept.endswith("\n") else "\n")


def main(argv: list[str]) -> int:
    """For install.sh: write settings-hub.conf (or settings-hub.lua) to OUT.

        python3 -m settings_hub.binds.writer conf OUT --data-home D --bin-home B [--keep FILE]
        python3 -m settings_hub.binds.writer lua OUT --data-home D --bin-home B

    --keep: an existing settings-hub.conf whose binds block is carried over
    verbatim (exit 3 if its markers are damaged; OUT is not written then).
    """
    usage = ("usage: writer conf OUT --data-home D --bin-home B [--keep FILE]\n"
             "       writer lua OUT --data-home D --bin-home B")
    if len(argv) < 2 or argv[0] not in ("conf", "lua"):
        print(usage, file=sys.stderr)
        return 2
    out, opts, rest = Path(argv[1]), {}, argv[2:]
    while rest:
        if len(rest) < 2 or rest[0] not in ("--data-home", "--bin-home", "--keep"):
            print(usage, file=sys.stderr)
            return 2
        opts[rest[0]], rest = rest[1], rest[2:]
    if "--data-home" not in opts or "--bin-home" not in opts:
        print(usage, file=sys.stderr)
        return 2
    data, bins = opts["--data-home"], opts["--bin-home"]
    if argv[0] == "lua":
        if "--keep" in opts:
            print(usage, file=sys.stderr)
            return 2
        out.write_text(lua_text(data, bins), encoding="utf-8")
        return 0
    keep = Path(opts["--keep"]) if "--keep" in opts else None
    if keep is not None and keep.exists():
        try:
            text = regenerate(keep.read_text(encoding="utf-8"), data, bins)
        except NoBlock:
            print(f"{keep}: the binds block markers are damaged ({BEGIN} ... {END}); "
                  "fix them or move the file away", file=sys.stderr)
            return 3
    else:
        text = conf_text(data, bins)
    out.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
