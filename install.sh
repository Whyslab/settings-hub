#!/bin/sh
# install.sh - install settings-hub for the current user.
#
#   ./install.sh --prefix DIR   install into a sandbox: every path is DIR + the
#                               usual path under your home directory
#
# This version installs into a sandbox only. Hooking into the live Hyprland
# session (reload, starting the background copy) is a separate, later step, so
# nothing here calls hyprctl or gdbus.
#
# Everything created is listed in $XDG_STATE_HOME/settings-hub/install-manifest
# (inside the sandbox); uninstall.sh removes exactly that and nothing else.

set -eu

die() { printf 'error: %s\n' "$*" >&2; exit 2; }
say() { printf '==> %s\n' "$*"; }
ok() { printf '  ok %s\n' "$*"; }

PREFIX=""
while [ $# -gt 0 ]; do
    case $1 in
        --prefix)
            [ $# -ge 2 ] && [ -n "$2" ] || die "--prefix needs a directory"
            PREFIX=${2%/}
            shift 2
            ;;
        -h | --help) sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) die "unknown argument: $1 (try --help)" ;;
    esac
done

[ -n "$PREFIX" ] || die "this version installs into a sandbox only: ./install.sh --prefix DIR"
[ "$(id -u)" -ne 0 ] || die "do not run this as root"
case $PREFIX in /*) ;; *) PREFIX=$PWD/$PREFIX ;; esac

SRC=$(cd "$(dirname "$0")" && pwd)

# Paths as they are in a real install (written into generated files) ...
DATA_HOME=${XDG_DATA_HOME:-$HOME/.local/share}
CONFIG_HOME=${XDG_CONFIG_HOME:-$HOME/.config}
STATE_HOME=${XDG_STATE_HOME:-$HOME/.local/state}
BIN_HOME=$HOME/.local/bin
# ... and where they land now.
APP_DIR=$PREFIX$DATA_HOME/settings-hub
BIN_DIR=$PREFIX$BIN_HOME
DESKTOP_DIR=$PREFIX$DATA_HOME/applications
HYPR_DIR=$PREFIX$CONFIG_HOME/hypr
STATE_DIR=$PREFIX$STATE_HOME/settings-hub
MANIFEST=$STATE_DIR/install-manifest
TAB=$(printf '\t')

say "Installing into ${PREFIX}"

# Directories that do not exist yet are recorded (outermost first) so the
# uninstaller removes exactly those, if they are empty by then.
NEW_MANIFEST=$(mktemp)
trap 'rm -f "$NEW_MANIFEST"' EXIT
record() { printf '%s\n' "$*" >>"$NEW_MANIFEST"; }

make_dir() {
    missing=""
    d=$1
    while [ ! -d "$d" ]; do
        missing="$d
$missing"
        d=$(dirname "$d")
    done
    mkdir -p "$1"
    printf '%s' "$missing" | while IFS= read -r m; do
        [ -n "$m" ] && record "dir$TAB$m"
    done
    return 0
}

put() { # put MODE SRC DEST
    make_dir "$(dirname "$3")"
    cp "$2" "$3"
    chmod "$1" "$3"
    record "file$TAB$3"
}

make_dir "$STATE_DIR"

put 755 "$SRC/app.py" "$APP_DIR/app.py"
(cd "$SRC" && find settings_hub -name '*.py' -not -path '*/__pycache__/*') | sort |
    while IFS= read -r f; do put 644 "$SRC/$f" "$APP_DIR/$f"; done
put 644 "$SRC/style/base.css" "$APP_DIR/style/base.css"
for f in "$SRC"/style/icons/*.svg; do
    put 644 "$f" "$APP_DIR/style/icons/$(basename "$f")"
done
ok "program in $APP_DIR"

put 755 "$SRC/bin/settings-open" "$BIN_DIR/settings-open"
put 755 "$SRC/uninstall.sh" "$BIN_DIR/settings-hub-uninstall"
ok "settings-open and settings-hub-uninstall in $BIN_DIR"

# Text comes from settings_hub/strings.py; the registry module needs no GTK.
registry() {
    (cd "$SRC" && PYTHONDONTWRITEBYTECODE=1 python3 -m settings_hub.registry "$@")
}
make_dir "$APP_DIR"
registry pages-json "$APP_DIR/pages.json"
record "file$TAB$APP_DIR/pages.json"
registry open-failed "$APP_DIR/open-failed.txt" --log "$STATE_HOME/settings-hub/app.log"
record "file$TAB$APP_DIR/open-failed.txt"
make_dir "$DESKTOP_DIR"
registry desktop "$DESKTOP_DIR/settings-hub.desktop" --exec "$BIN_HOME/settings-open"
record "file$TAB$DESKTOP_DIR/settings-hub.desktop"
ok "pages.json, settings-hub.desktop"

make_dir "$HYPR_DIR"
cat >"$HYPR_DIR/settings-hub.conf" <<EOF
# Generated by settings-hub. The binds block is edited by the Settings window.
exec-once = python3 $DATA_HOME/settings-hub/app.py --daemon
windowrule = match:class ^(settings-hub|io\\.github\\.whyslab\\.SettingsHub)\$, float true, size 920 640, center true
unbind = SUPER SHIFT, N
bind   = SUPER SHIFT, N, exec, $BIN_HOME/settings-open screen-sleep
unbind = SUPER SHIFT, W
bind   = SUPER SHIFT, W, exec, $BIN_HOME/settings-open wallpaper
bind   = SUPER, I, exec, $BIN_HOME/settings-open
submap = settings-hub-capture
bind   = SUPER CTRL ALT, Escape, submap, reset
submap = reset
# >>> settings-hub binds
# <<< settings-hub binds
EOF
record "file$TAB$HYPR_DIR/settings-hub.conf"
ok "settings-hub.conf"

# One line at the end of hyprland.conf, if there is one: a dated copy first,
# then append the line unless it is already there. The manifest remembers
# whether a final newline had to be added, so removal restores the file byte
# for byte.
HYPR_CONF=$HYPR_DIR/hyprland.conf
if [ "$CONFIG_HOME" = "$HOME/.config" ]; then
    # Hyprland expands the tilde itself; the line stays readable this way.
    # shellcheck disable=SC2088
    conf_ref="~/.config/hypr/settings-hub.conf"
else
    conf_ref="$CONFIG_HOME/hypr/settings-hub.conf"
fi
LINE="source = $conf_ref  # settings-hub"
if [ -f "$HYPR_CONF" ]; then
    backup="$HYPR_CONF.bak-$(date +%Y%m%d)-settings-hub"
    [ -e "$backup" ] || cp -p "$HYPR_CONF" "$backup"
    if grep -Fxq "$LINE" "$HYPR_CONF"; then
        previous=$(grep "^line$TAB$HYPR_CONF$TAB" "$MANIFEST" 2>/dev/null | head -n 1) || true
        if [ -n "$previous" ]; then
            record "$previous"
        else
            record "line$TAB$HYPR_CONF$TAB$LINE${TAB}0"
        fi
        ok "hyprland.conf already sources settings-hub.conf"
    else
        added_newline=0
        if [ -s "$HYPR_CONF" ] && [ "$(tail -c 1 "$HYPR_CONF" | od -An -c | tr -d ' ')" != '\n' ]; then
            printf '\n' >>"$HYPR_CONF"
            added_newline=1
        fi
        printf '%s\n' "$LINE" >>"$HYPR_CONF"
        record "line$TAB$HYPR_CONF$TAB$LINE$TAB$added_newline"
        ok "hyprland.conf: added one line (copy: $(basename "$backup"))"
    fi
fi

# A reinstall replaces the manifest; files the old one listed that this
# version no longer ships are removed now.
if [ -f "$MANIFEST" ]; then
    grep "^file$TAB" "$MANIFEST" | cut -f 2 | while IFS= read -r old; do
        if ! grep -Fxq "file$TAB$old" "$NEW_MANIFEST"; then
            case $old in "$PREFIX"/*) rm -f -- "$old" ;; esac
        fi
    done
    grep "^dir$TAB" "$MANIFEST" | while IFS= read -r entry; do
        grep -Fxq "$entry" "$NEW_MANIFEST" || record "$entry"
    done
fi
cp "$NEW_MANIFEST" "$MANIFEST"
chmod 644 "$MANIFEST"
ok "manifest: $MANIFEST"
say "Sandbox install finished"
